const path = require('path');
const fs = require('fs');
const http = require('http');
const { Socket } = require('net');
const { build } = require('vite');
const Y = require('yjs');

const rootDir = path.resolve(__dirname, '..');

function mockExpressCall(app, method, urlPath, body = null) {
  return new Promise((resolve, reject) => {
    const socket = new Socket();
    const req = new http.IncomingMessage(socket);
    req.method = method.toUpperCase();
    req.url = urlPath;
    req.headers = {
      'content-type': 'application/json',
      host: 'localhost:4000',
    };
    req.body = body;

    const res = new http.ServerResponse(req);
    res.assignSocket(socket);

    let payload = '';
    res.write = function (chunk, encoding, cb) {
      if (chunk) payload += chunk.toString();
      if (cb) cb();
      return true;
    };

    res.end = function (chunk, encoding, cb) {
      if (chunk) payload += chunk.toString();
      let json = null;
      try {
        json = JSON.parse(payload);
      } catch (e) {}
      resolve({ status: res.statusCode, data: payload, json });
    };

    app.handle(req, res, (err) => {
      if (err) reject(err);
    });
  });
}

async function runTestSuite() {
  console.log('====================================================');
  console.log('STARTING REAL-TIME COLLABORATIVE WORKSPACE TEST SUITE');
  console.log('====================================================\n');

  console.log('--- TEST 1: React + TypeScript Vite Production Build ---');
  await build({
    root: rootDir,
    configFile: path.join(rootDir, 'vite.config.mjs'),
    logLevel: 'warn',
  });
  const distHtml = path.join(rootDir, 'dist', 'index.html');
  if (!fs.existsSync(distHtml)) {
    throw new Error('dist/index.html was not generated by Vite build.');
  }
  console.log('PASS: Vite compiled React SPA client successfully.\n');

  console.log('--- TEST 2: Initializing Express Backend & API Routes ---');
  const serverModule = require(path.join(rootDir, 'server.js'));
  const app = serverModule.app;
  if (!app) {
    throw new Error('Express app was not exported by server.js');
  }
  console.log('PASS: Express app initialized with full middleware stack.\n');

  console.log('--- TEST 3: Health & Tech Stack Inspection ---');
  const healthRes = await mockExpressCall(app, 'GET', '/api/health');
  if (healthRes.status !== 200) throw new Error(`Expected 200, got ${healthRes.status}`);
  console.log('PASS: GET /api/health returned 200 OK.');

  const apiRes = await mockExpressCall(app, 'GET', '/api');
  if (apiRes.status !== 200) throw new Error(`Expected 200, got ${apiRes.status}`);
  const apiData = JSON.parse(apiRes.data);
  const requiredStack = ['React', 'TypeScript', 'Node.js', 'Express', 'PostgreSQL', 'Prisma', 'Zod', 'Docker'];
  for (const tech of requiredStack) {
    if (!apiData.techStack.includes(tech)) {
      throw new Error(`Tech stack missing required component: ${tech}`);
    }
  }
  console.log('PASS: GET /api verified required tech stack:', requiredStack.join(', '), '\n');

  console.log('--- TEST 4: Document CRUD & Persistence ---');
  const docsRes = await mockExpressCall(app, 'GET', '/api/documents');
  if (docsRes.status !== 200) throw new Error(`Expected 200, got ${docsRes.status}`);
  const docs = JSON.parse(docsRes.data);
  if (!Array.isArray(docs) || docs.length === 0) {
    throw new Error('Expected documents list to contain pre-seeded documents.');
  }
  console.log(`PASS: GET /api/documents returned ${docs.length} document(s).`);

  const singleDocRes = await mockExpressCall(app, 'GET', `/api/documents/${docs[0].id}`);
  if (singleDocRes.status !== 200) throw new Error(`Expected 200, got ${singleDocRes.status}`);
  console.log(`PASS: GET /api/documents/${docs[0].id} returned document with blocks.\n`);

  console.log('--- TEST 5: Canvas Whiteboard CRUD & Persistence ---');
  const canvasRes = await mockExpressCall(app, 'GET', '/api/canvases');
  if (canvasRes.status !== 200) throw new Error(`Expected 200, got ${canvasRes.status}`);
  const canvases = JSON.parse(canvasRes.data);
  if (!Array.isArray(canvases) || canvases.length === 0) {
    throw new Error('Expected canvases list to contain pre-seeded canvas.');
  }
  console.log(`PASS: GET /api/canvases returned ${canvases.length} canvas(es).`);

  const singleCanvasRes = await mockExpressCall(app, 'GET', `/api/canvases/${canvases[0].id}`);
  if (singleCanvasRes.status !== 200) throw new Error(`Expected 200, got ${singleCanvasRes.status}`);
  console.log(`PASS: GET /api/canvases/${canvases[0].id} returned canvas with elements.\n`);

  console.log('--- TEST 6: Zod Runtime Schema Validation ---');
  const invalidDocRes = await mockExpressCall(app, 'POST', '/api/documents', { title: '' });
  if (invalidDocRes.status !== 400) {
    throw new Error(`Expected 400 Bad Request for invalid body, got ${invalidDocRes.status}`);
  }
  const invalidJson = JSON.parse(invalidDocRes.data);
  if (!invalidJson.error || !invalidJson.details) {
    throw new Error('Expected Zod error details in response.');
  }
  console.log('PASS: Zod rejected invalid payload with HTTP 400 and structured error details.');

  const validDocRes = await mockExpressCall(app, 'POST', '/api/documents', {
    title: 'Automated Test Document',
    icon: '📄',
    workspaceId: 'default-workspace',
  });
  if (validDocRes.status !== 201) {
    throw new Error(`Expected 201 Created, got ${validDocRes.status}`);
  }
  const createdDoc = JSON.parse(validDocRes.data);
  console.log(`PASS: Zod validated and created new document (ID: ${createdDoc.id}).\n`);

  console.log('--- TEST 7: React SPA Static Asset Serving ---');
  const spaRes = await mockExpressCall(app, 'GET', '/');
  if (spaRes.status !== 200) throw new Error(`Expected 200 for root, got ${spaRes.status}`);
  if (!spaRes.data.includes('<div id="root"></div>')) {
    throw new Error('Response did not contain React root element.');
  }
  console.log('PASS: Root path serves React SPA index.html with HTML5 mounting point.\n');

  console.log('--- TEST 8: Real-Time CRDT State Synchronization (Yjs) ---');
  const docA = new Y.Doc();
  const docB = new Y.Doc();

  const textA = docA.getText('content');
  const textB = docB.getText('content');

  textA.insert(0, 'Hello from Collaborator 1');

  const update1 = Y.encodeStateAsUpdate(docA);
  Y.applyUpdate(docB, update1);

  if (textB.toString() !== 'Hello from Collaborator 1') {
    throw new Error('Yjs CRDT synchronization failed between Peer A and Peer B.');
  }

  textB.insert(textB.length, ' & Collaborator 2');
  const update2 = Y.encodeStateAsUpdate(docB);
  Y.applyUpdate(docA, update2);

  if (textA.toString() !== 'Hello from Collaborator 1 & Collaborator 2') {
    throw new Error('Yjs bi-directional merge failed.');
  }
  console.log('PASS: Yjs CRDT conflict-free peer state synchronization verified.\n');

  console.log('====================================================');
  console.log('ALL TESTS PASSED! PROJECT IS WORKING PROPERLY (100%)');
  console.log('====================================================\n');
}

runTestSuite()
  .then(() => {
    process.exit(0);
  })
  .catch((err) => {
    console.error('\nTEST RUNNER ERROR:', err);
    process.exit(1);
  });
